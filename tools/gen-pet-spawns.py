"""Generates src/renderer/src/data/petSpawns.ts (pet spawn points per map) from a PetTracker checkout.

Usage: python tools/gen-pet-spawns.py <path to PetTracker-main>

Only facts are taken: which NPC (and so which pet) spawns where, as map-relative coordinates (0..1), for the two regions
PetTracker ships (Verteron, Altgard). The coordinates are an approximate fit published by SkeeveAN/Aion-DPS-Meter
(GPL-3.0) and used by PetTracker (GPL-3.0); they are not verified in game.
"""
import json
import sys
from pathlib import Path

root = Path(sys.argv[1])
regions = json.loads((root / 'src' / 'Core' / 'FarmingSpawns.json').read_text(encoding='utf-8-sig'))

names = {}
out_regions = []
for r in regions:
    points = []
    for p in r['Points']:
        names[p['NpcId']] = p['Name']
        points.append([p['PetId'], p['NpcId'], round(p['X'], 4), round(p['Y'], 4)])
    out_regions.append({
        'key': r['Key'],
        'name': r['Name'],
        'grid': r['Grid'],
        'tiles': [[t['Column'], t['Row']] for t in r['Tiles']],
        'points': points,
    })

lines = [
    '// Generated by tools/gen-pet-spawns.py from PetTracker (GPL-3.0). Approximate static spawn points, not live mobs.',
    '// points: [pet id, npc id, x, y] with x, y in 0..1 over the whole map',
    'export interface SpawnRegion {',
    '  key: string;',
    '  name: string;',
    '  grid: number;',
    '  tiles: [number, number][];',
    '  points: [number, number, number, number][];',
    '}',
    '',
    f'export const SPAWN_REGIONS: SpawnRegion[] = {json.dumps(out_regions, ensure_ascii=False, separators=(",", ":"))};',
    '',
    f'export const SPAWN_NPC_NAMES: Record<number, string> = {json.dumps({str(k): v for k, v in sorted(names.items())}, ensure_ascii=False, separators=(",", ":"))};',
    '',
]
dest = Path('src/renderer/src/data/petSpawns.ts')
dest.parent.mkdir(parents=True, exist_ok=True)
dest.write_text('\n'.join(lines), encoding='utf-8')
print(len(out_regions), 'regions,', sum(len(r['points']) for r in out_regions), 'points,', len(names), 'npc names,', dest.stat().st_size // 1024, 'KB')
