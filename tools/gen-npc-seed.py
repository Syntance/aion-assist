"""Generates src/main/data/npcSeed.ts (the built-in table of NPC / boss / dungeon names) from Aion2DPSMeter's data files.

Usage: python tools/gen-npc-seed.py <npcs.en.json> <dungeons.en.json>
(get them from https://github.com/domel1998/Aion2DPSMeter/tree/main/data, GPL-3.0)

The game only sends numeric NPC codes; these tables map them to the English names and mark the bosses.
"""
import json
import sys
from pathlib import Path

npcs_in = json.loads(Path(sys.argv[1]).read_text(encoding='utf-8'))
dungeons_in = json.loads(Path(sys.argv[2]).read_text(encoding='utf-8'))

npcs = {}
for code, v in npcs_in.items():
    name = (v.get('name') or '').strip()
    if not name:
        continue
    entry = {'name': name}
    if v.get('isBoss') is True:
        entry['boss'] = True
    npcs[code] = entry
dungeons = {code: {'name': v['name'].strip()} for code, v in dungeons_in.items() if (v.get('name') or '').strip()}

lines = [
    '// Generated by tools/gen-npc-seed.py from Aion2DPSMeter (GPL-3.0, domel1998). Names of NPCs, bosses and dungeons.',
    "import type { CatalogData } from '../catalog';",
    '',
    f'export const NPC_SEED: CatalogData = {json.dumps({"npcs": npcs, "dungeons": dungeons}, ensure_ascii=False, separators=(",", ":"))};',
    '',
]
dest = Path('src/main/data/npcSeed.ts')
dest.parent.mkdir(parents=True, exist_ok=True)
dest.write_text('\n'.join(lines), encoding='utf-8')
print(len(npcs), 'npcs,', sum(1 for n in npcs.values() if n.get('boss')), 'bosses,', len(dungeons), 'dungeons,', dest.stat().st_size // 1024, 'KB')
