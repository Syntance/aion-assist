"""Generates src/core/pets/petData.ts from the PetTracker source tree (GPLv3, github.com/0Fox2Give/PetTracker).

Usage: python tools/gen-pet-data.py <path to PetTracker-main> 
Only facts are taken (pet ids/names/families, which NPC drops which pet, how a pet is obtained); no code or artwork.
"""
import json
import sys
from collections import defaultdict
from pathlib import Path

root = Path(sys.argv[1])
catalog = json.loads((root / 'assets' / 'catalog.json').read_text(encoding='utf-8'))
sources = json.loads((root / 'src' / 'Core' / 'PetSources.json').read_text(encoding='utf-8-sig'))
acq = json.loads((root / 'src' / 'Core' / 'PetAcquisitions.json').read_text(encoding='utf-8-sig'))

FAMILY = {'Intellect': 'Cogni', 'Feral': 'Fera', 'Nature': 'Natura', 'Trans': 'Varian', 'Special': 'Special'}
by_id = {c['Id']: c for c in catalog}

paid = {a['PetId'] for a in acq if a.get('RealMoneyOnly')}
pets = [[c['Id'], c['Name'], FAMILY.get(c['Category'], ''), 1 if c['Id'] in paid else 0] for c in catalog]

# NPC -> pet: only when every source row of that NPC names the same pet and the catalog name agrees
groups = defaultdict(list)
for row in sources['Rows']:
    groups[row['NpcId']].append(row)
npc = {}
for npc_id, rows in groups.items():
    claims = {(r['PetId'], r['CatalogName']) for r in rows}
    if len(claims) != 1:
        continue
    pet_id, cat_name = next(iter(claims))
    if pet_id in by_id and by_id[pet_id]['CatalogName'] == cat_name:
        npc[npc_id] = [pet_id, rows[0]['NpcName']]
for npc_id, pet_id, cat_name in ((2100034, 1008, 'OdSpider_01'), (2100231, 1168, 'WaterEle_01'), (2400240, 1163, 'Basilisk_01')):
    if pet_id in by_id and by_id[pet_id]['CatalogName'] == cat_name:
        npc[npc_id] = [pet_id, npc.get(npc_id, [0, f'NPC #{npc_id}'])[1]]

source = {a['PetId']: [a['Kind'], a['Instructions']] for a in acq}

out = [
    '// Generated by tools/gen-pet-data.py from PetTracker (GPLv3, 0Fox2Give). Facts only: ids, names, drop sources.',
    '// [id, name, family, paidOnly]',
    f'export const PET_ROWS: readonly (readonly [number, string, string, number])[] = {json.dumps(pets, ensure_ascii=False)};',
    '',
    '/** NPC code -> [pet id, NPC name]. */',
    f'export const NPC_PETS: Readonly<Record<number, readonly [number, string]>> = {json.dumps({str(k): v for k, v in sorted(npc.items())}, ensure_ascii=False)};',
    '',
    '/** Pet id -> [kind, how to get it]. */',
    f'export const PET_SOURCES: Readonly<Record<number, readonly [string, string]>> = {json.dumps({str(k): v for k, v in sorted(source.items())}, ensure_ascii=False)};',
    '',
]
Path('src/core/pets/petData.ts').write_text('\n'.join(out), encoding='utf-8')
print(len(pets), 'pets;', len(npc), 'npcs;', len(source), 'sources;', len(paid), 'paid-only')
